function timeline(
  entries: Array<[StageKey, string, string, string]>,
  currentStage: StageKey,
): Batch["timeline"] {
  const currentIdx = STAGE_ORDER.indexOf(currentStage);
  return entries.map(([stage, timestamp, location, note]) => {
    const idx = STAGE_ORDER.indexOf(stage);
    return {
      stage,
      timestamp,
      location,
      note,
      status:
        idx < currentIdx ? "selesai" : idx === currentIdx ? "berjalan" : "menunggu",
    };
  });
}

