/**
 * revenueYtd dan coverage sengaja diturunkan, bukan ditulis manual,
 * supaya total nasional selalu cocok dengan penjumlahan per wilayah.
 */
export const regions: Region[] = SEEDS.map((s) => {
  const beneficiaries = Math.round(s.unitsSoldYtd / SACHETS_PER_BENEFICIARY_YTD);
  return {
    id: s.id,
    name: s.name,
    island: s.island,
    status: s.status,
    phase: s.phase,
    targetPopulation: s.targetPopulation,
    stuntingRate: s.stuntingRate,
    nutritionGapIndex: s.nutritionGapIndex,
    logisticsDifficulty: s.logisticsDifficulty,
    outlets: s.outlets,
    coverage:
      s.targetPopulation > 0
        ? Math.round((beneficiaries / s.targetPopulation) * 1000) / 10
        : 0,
    unitsSoldYtd: s.unitsSoldYtd,
    revenueYtd: s.unitsSoldYtd * s.asp,
    partners: s.partners,
    lastShipment: s.lastShipment,
  };
});

export const regionById = new Map(regions.map((r) => [r.id, r]));

export const TOTAL_UNITS_YTD = regions.reduce((a, r) => a + r.unitsSoldYtd, 0);
export const TOTAL_REVENUE_YTD = regions.reduce((a, r) => a + r.revenueYtd, 0);
export const TOTAL_OUTLETS = regions.reduce((a, r) => a + r.outlets, 0);
export const TOTAL_BENEFICIARIES = Math.round(
  TOTAL_UNITS_YTD / SACHETS_PER_BENEFICIARY_YTD,
);

